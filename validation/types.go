var (
	ErrValidationFailed = errors.New("dicom validation failed")
	ErrInvalidPolicy    = errors.New("dicom validation policy is invalid")
	ErrHookFailed       = errors.New("dicom validation hook failed")
	ErrHookAction       = errors.New("dicom validation hook action is invalid for this lifecycle point")
	ErrValidationLimit  = errors.New("dicom validation resource limit exceeded")
)

type Mode uint8

const (
	// ModePreserve collects findings without changing their severity or
	// rejecting the caller-owned data set. It is the zero value.
	ModePreserve Mode = iota
	// ModeWarn downgrades validation errors to warnings and preserves data.
	ModeWarn
	// ModeStrict returns ErrValidationFailed when an error finding is emitted.
	ModeStrict
)

